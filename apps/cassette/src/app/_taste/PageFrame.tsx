"use client";

/**
 * The taste page frame, one for every page on the site's paper (all but the desk's and the dashboard's
 * app shells): the paper, the reveal observer, the masthead (fixed over the page; the body leaves its
 * room at the top), the page in a size container (`taste`, which pages query at 760 and 1100), the
 * footer, and with `player` the one preview player and its dock. Inside the iPhone app
 * (lib/app-surface.ts) the masthead and footer step aside and the paper stays.
 *
 * `player`: the artist and album pages share the frame as their layout with the player on, and next/link
 * keeps that layout mounted between them, which is what keeps a song playing. A page without it never
 * asks YouTube for anything.
 *
 * `oldKit`: the page inside is still drawn in the old kit (src/app/components, src/app/sections, the --cs-
 * tokens). Its body writes the old role names from this paper's roles (the `cs` set, generated by
 * packages/cassette-kit from the same tokens as the taste roles) and sets its text in the body face, so
 * it sits on the new paper in the new inks without a change of its own until its wave redraws it.
 *
 * `account={false}` drops the masthead's account end (Sign in, or Library and the account key) on a page
 * that is itself the way in (the account pages).
 *
 * The paper follows the reader's device on every page, the light card stock or the dark paper
 * (taste.module.css, .follows), and the reader's own choice in Appearance wins over the device (<html
 * data-paper>, lib/appearance.ts). Inside the iPhone app it holds dark while the app is dark-only
 * (lib/app-surface.ts, the one switch for that). A review link can hold one (?paper=light or ?paper=dark),
 * from the moment the page starts on the client. `data-follows` tells the page under the paper and the
 * browser's own colours (the root layout) to follow too.
 *
 * PageHead is a page's own head on the paper: its title, a dateline, and a lede under it.
 */

import { useEffect, useRef, type ReactNode, type RefObject } from "react";
import { Footer } from "./Footer";
import { Masthead } from "./Masthead";
import { PlayerDock } from "./PlayerDock";
import { PlayerProvider } from "./player";
import { useReveal } from "./reveal";
import t from "./taste.module.css";
import f from "./frame.module.css";

type Body = { oldKit?: boolean; account?: boolean; children: ReactNode };

/** A review link's paper (?paper=light or ?paper=dark). */
export function useReviewPaper(rootRef: RefObject<HTMLDivElement | null>) {
  useEffect(() => {
    const asked = new URLSearchParams(window.location.search).get("paper");
    if (rootRef.current && (asked === "light" || asked === "dark")) rootRef.current.dataset.paper = asked;
  }, [rootRef]);
}

function Paper({ oldKit, account = true, rootRef, dock, children }: Body & { rootRef: RefObject<HTMLDivElement | null>; dock?: ReactNode }) {
  useReveal(rootRef);
  useReviewPaper(rootRef);
  return (
    <div ref={rootRef} id="top" className={`${t.root} ${t.follows}`} data-follows="">
      <Masthead home="/" account={account} />
      <main className={oldKit ? `${t.body} ${f.oldKit}` : t.body} data-old-kit={oldKit ? "" : undefined}>
        {children}
      </main>
      <Footer />
      {dock}
    </div>
  );
}

function Plain(props: Body) {
  const rootRef = useRef<HTMLDivElement>(null);
  return <Paper {...props} rootRef={rootRef} />;
}

function WithPlayer(props: Body) {
  const rootRef = useRef<HTMLDivElement>(null);
  return <Paper {...props} rootRef={rootRef} dock={<PlayerDock rootRef={rootRef} />} />;
}

export function PageFrame({ player, oldKit, account, children }: Body & { player?: boolean }) {
  return player ? (
    <PlayerProvider>
      <WithPlayer oldKit={oldKit} account={account}>
        {children}
      </WithPlayer>
    </PlayerProvider>
  ) : (
    <Plain oldKit={oldKit} account={account}>
      {children}
    </Plain>
  );
}

/** A page's head on the paper: an eyebrow over it in the label type, its title in the head role, a
 *  dateline under the title in the label type (a document's "last updated"), and a lede in the body face.
 *  `wrap={false}` when the page already sits in its own column (help's article beside its topics). */
export function PageHead({
  eyebrow,
  title,
  meta,
  lede,
  wrap = true,
}: {
  eyebrow?: ReactNode;
  title: ReactNode;
  meta?: ReactNode;
  lede?: ReactNode;
  wrap?: boolean;
}) {
  return (
    <header className={wrap ? `${t.wrap} ${f.head}` : f.head}>
      {eyebrow ? <p className={f.eyebrow}>{eyebrow}</p> : null}
      <h1 className={f.title}>{title}</h1>
      {meta ? <p className={f.eyebrow}>{meta}</p> : null}
      {lede && <p className={f.lede}>{lede}</p>}
    </header>
  );
}
