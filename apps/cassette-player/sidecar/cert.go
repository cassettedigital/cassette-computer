// loadTLSConfig builds a *tls.Config that HOT-RELOADS the cert per handshake via
// GetCertificate (cert auto-renewal), or returns a nil config when no cert is
// available (the server then serves plain HTTP only). When the renewal loop
// writes a fresh cert into the data dir, the next TLS handshake picks it up with
// NO restart. Returns the path currently in use for logging.
func loadTLSConfig() (cfg *tls.Config, certPath string, err error) {
	// Is any usable cert present at all (data-dir preferred, bundled fallback)?
	certPath, _, err = activeCertProvider.Locate()
	if err != nil {
		return nil, "", err
	}
	if certPath == "" {
		return nil, "", nil // no cert → HTTP-only
	}
	reloader, err := newCertReloader(certSearchDirs())
	if err != nil {
		return nil, "", err
	}
	return &tls.Config{
		GetCertificate: reloader.GetCertificate,
		MinVersion:     tls.VersionTLS12,
	}, certPath, nil
}

// certReloader serves the current cert per TLS handshake, reloading from disk
// when the chosen cert file changes. dirs are searched in order (data-dir first
// = the renewable seam; bundled fallback last), so a renewal written into the
// data dir is served on the next handshake — and a first-run install on the
// bundled cert transparently switches to the data-dir cert once one lands.
type certReloader struct {
	dirs        []string
	mu          sync.Mutex
	cached      *tls.Certificate
	loadedPath  string
	loadedMtime time.Time
}

func newCertReloader(dirs []string) (*certReloader, error) {
	r := &certReloader{dirs: dirs}
	if _, err := r.current(); err != nil {
		return nil, err
	}
	return r, nil
}

// current returns the up-to-date cert, reloading if the chosen file changed or
// the chosen dir switched (bundled → data-dir). A failed reload keeps the last
// good cert rather than dropping TLS.
func (r *certReloader) current() (*tls.Certificate, error) {
	var certPath, keyPath string
	var mtime time.Time
	for _, d := range r.dirs {
		c := filepath.Join(d, certFileName)
		k := filepath.Join(d, keyFileName)
		if fi, err := os.Stat(c); err == nil && !fi.IsDir() && fi.Size() > 0 && fileNonEmpty(k) {
			certPath, keyPath, mtime = c, k, fi.ModTime()
			break
		}
	}

	r.mu.Lock()
	defer r.mu.Unlock()
	if certPath == "" {
		if r.cached != nil {
			return r.cached, nil
		}
		return nil, fmt.Errorf("no cert available in %v", r.dirs)
	}
	if r.cached != nil && r.loadedPath == certPath && !mtime.After(r.loadedMtime) {
		return r.cached, nil // unchanged
	}
	pair, err := tls.LoadX509KeyPair(certPath, keyPath)
	if err != nil {
		if r.cached != nil {
			log.Printf("cert reload failed (keeping current): %v", err)
			return r.cached, nil
		}
		return nil, err
	}
	if r.cached != nil {
		log.Printf("cert hot-reloaded from %s", certPath)
	}
	r.cached, r.loadedPath, r.loadedMtime = &pair, certPath, mtime
	return &pair, nil
}

func (r *certReloader) GetCertificate(*tls.ClientHelloInfo) (*tls.Certificate, error) {
	return r.current()
}

// serveLocal runs srv on addr. When a cert is present it serves HTTPS and plain
// HTTP on the SAME port (see the package doc for why both are required); with no
// cert it serves plain HTTP only. Blocks until the server stops — run it in a
// goroutine.
func serveLocal(srv *http.Server, addr string) {
	ln, err := net.Listen("tcp", addr)
	if err != nil {
		log.Printf("Local server: cannot listen on %s: %v", addr, err)
		return
	}

	tlsCfg, certPath, err := loadTLSConfig()
	if err != nil {
		log.Printf("Local server: cert problem (%v) — serving plain HTTP on %s", err, addr)
	}
	if tlsCfg != nil {
		log.Printf("Local server: serving HTTPS + HTTP on %s (provider: %s, cert: %s)",
			addr, activeCertProvider.Name(), certPath)
		ln = &splitListener{Listener: ln, tlsConfig: tlsCfg}
	} else {
		log.Printf("Local server: no cert (provider: %s) — serving plain HTTP on %s",
			activeCertProvider.Name(), addr)
	}

	if err := srv.Serve(ln); err != http.ErrServerClosed {
		log.Printf("Local server error: %v", err)
	}
}

// ── One-port TLS/plaintext demux ─────────────────────────────────────────────

// splitListener sniffs the first byte of each accepted connection and wraps it
// in TLS when it looks like a handshake (record type 0x16), leaving plain HTTP
// untouched. Both kinds are handed to the same http.Server (which has no
// TLSConfig of its own — the TLS happens at the conn layer here).
type splitListener struct {
	net.Listener
	tlsConfig *tls.Config
}

func (l *splitListener) Accept() (net.Conn, error) {
	for {
		conn, err := l.Listener.Accept()
		if err != nil {
			return nil, err // genuine listener error → let the server handle it
		}
		sniffed, isTLS, perr := sniffTLS(conn)
		if perr != nil {
			// A client that connected but sent nothing readable in time. Drop
			// it and keep accepting rather than killing the whole server.
			conn.Close()
			continue
		}
		if isTLS {
			return tls.Server(sniffed, l.tlsConfig), nil
		}
		return sniffed, nil
	}
}

// sniffTLS reads the first byte (with a short deadline so a silent client can't
// stall the accept loop) and returns a conn that replays it, plus whether the
// byte is a TLS handshake record type.
func sniffTLS(conn net.Conn) (net.Conn, bool, error) {
	_ = conn.SetReadDeadline(time.Now().Add(15 * time.Second))
	defer func() { _ = conn.SetReadDeadline(time.Time{}) }()

	b := make([]byte, 1)
	if _, err := io.ReadFull(conn, b); err != nil {
		return conn, false, err
	}
	return &prefixConn{Conn: conn, prefix: b}, b[0] == 0x16, nil
}

// prefixConn replays bytes consumed during sniffing before the underlying
// stream, so the wrapped reader (TLS handshake or HTTP parser) sees them.
type prefixConn struct {
	net.Conn
	prefix []byte
}

func (c *prefixConn) Read(p []byte) (int, error) {
	if len(c.prefix) > 0 {
		n := copy(p, c.prefix)
		c.prefix = c.prefix[n:]
		return n, nil
	}
	return c.Conn.Read(p)
}
