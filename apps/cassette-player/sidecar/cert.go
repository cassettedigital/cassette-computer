// Local HTTPS identity (CD-Rip portal, Job 1). RETIRED as a product path on
// 2026-10-29: the website no longer reaches the hub from a browser (cors.go), the
// shared local.cassette.digital certificate is no longer handed out or renewed
// (the backend's /api/player/cert answers 410, the renewal cron is gone), and the
// desktop app reaches its hub over plain loopback HTTP through /sidecar. No copy
// of the app ships a certificate. What stays is the listener below, which still
// serves HTTPS when a cert happens to sit in the data folder (a developer's own,
// minted by native/issue-cert.sh) and plain HTTP otherwise, which is every copy.
//
// Originally: the sidecar presented a publicly-trusted TLS cert so the hosted
// dashboard (an HTTPS origin) could fetch https://local.cassette.digital:5173
// with no mixed-content block and no warning.
//
// Why one port serves BOTH HTTPS and plain HTTP: the OAuth pairing callback is
// pinned server-side to http://localhost:<port>/callback (auth-confirm regex on
// cassette.digital), and the local :5173/rip station + wizard are plain HTTP
// too. A TLS-only :5173 would break all of those. So serveLocal sniffs the
// first byte of each connection — a TLS handshake starts with 0x16 — and routes
// TLS conns through the cert while plain-HTTP conns pass straight to the same
// mux. Pairing/wizard/station keep working unchanged over loopback; the
// dashboard gets trusted HTTPS over the hostname.
//
// Swap boundary (stated requirement): cert ACQUISITION lives behind the
// certProvider interface so a per-device ACME implementation can replace the
// shared wildcard cert later WITHOUT touching the server, CORS, or rip handlers.
// Today sharedFileCert just locates a wildcard cert dropped on disk; a future
// perDeviceACME provider implements the same Locate() by running ACME itself
// and writing the same two files. Nothing downstream changes.

package main

import (
	"crypto/tls"
	"fmt"
	"io"
	"log"
	"net"
	"net/http"
	"os"
	"path/filepath"
	"sync"
	"time"
)

// certProvider yields the cert + key the local HTTPS server presents. The only
// thing a provider promises is "here are usable cert+key paths, or nothing."
type certProvider interface {
	// Locate returns absolute paths to a usable cert + key, or ("", "", nil)
	// when none is present (the caller then falls back to plain HTTP). A
	// non-nil error means a present-but-broken config worth surfacing rather
	// than silently downgrading.
	Locate() (certPath, keyPath string, err error)
	// Name is a short human label for startup logs.
	Name() string
}

// certSearchDirs is the ordered list of directories the server looks in for a
// cert+key pair, first hit wins:
//  1. SIDECAR_CERT_DIR (default <data dir>/certs) — where native/issue-cert.sh
//     writes, so a re-issue/renewal is picked up on the next restart.
//  2. SIDECAR_BUNDLED_CERT_DIR — the copy build-app.sh bakes into the .app's
//     Resources/certs, so a freshly-installed .app serves HTTPS with nothing
//     re-run. The data-dir copy deliberately takes precedence so renewal never
//     requires rebuilding the bundle.
// sidecarCertDir is the data-dir cert location (first in the search order),
// where a developer's own cert goes. Nothing writes here any more: the renewal
// loop that did was retired on 2026-10-29.
var sidecarCertDir = envOr("SIDECAR_CERT_DIR", filepath.Join(sidecarDataDir, "certs"))

func certSearchDirs() []string {
	dirs := []string{sidecarCertDir}
	if b := os.Getenv("SIDECAR_BUNDLED_CERT_DIR"); b != "" {
		dirs = append(dirs, b)
	}
	return dirs
}

const (
	certFileName = "cert.pem"
	keyFileName  = "key.pem"
)

// sharedFileCert is the foundation provider: it locates a cert (SAN over both
// local.cassette.digital and *.local.cassette.digital) issued out-of-band into
// one of dirs. No acquisition logic — that's deliberately external for now so
// the shared key isn't generated by the shipped binary.
type sharedFileCert struct{ dirs []string }

func (s sharedFileCert) Name() string { return "shared-file" + fmt.Sprint(s.dirs) }

func (s sharedFileCert) Locate() (string, string, error) {
	var firstErr error
	for _, dir := range s.dirs {
		cert := filepath.Join(dir, certFileName)
		key := filepath.Join(dir, keyFileName)
		cOK := fileNonEmpty(cert)
		kOK := fileNonEmpty(key)
		switch {
		case cOK && kOK:
			return cert, key, nil
		case cOK != kOK && firstErr == nil:
			// One half of the pair present is a misconfiguration; remember it
			// (so we surface it if no later dir has a complete pair) instead of
			// silently serving HTTP and looking "fine."
			firstErr = fmt.Errorf("incomplete cert pair in %s (cert present=%v, key present=%v)", dir, cOK, kOK)
		}
	}
	return "", "", firstErr // no complete pair anywhere → HTTP fallback (or the flagged misconfig)
}

func fileNonEmpty(p string) bool {
	fi, err := os.Stat(p)
	return err == nil && !fi.IsDir() && fi.Size() > 0
}

// activeCertProvider is the provider the local server uses. Swapping to
// per-device ACME later is a one-line change here plus a new file implementing
// certProvider — see the TODO below.
var activeCertProvider certProvider = sharedFileCert{dirs: certSearchDirs()}

// TODO(per-device ACME): add a perDeviceACME certProvider whose Locate() runs
// an ACME DNS-01 flow for <device-id>.local.cassette.digital (covered by the
// same wildcard DNS) and caches the result in sidecarCertDir, then set
// activeCertProvider to it. The shared wildcard *.local.cassette.digital DNS
// record already accommodates the per-device names, so this upgrade touches
